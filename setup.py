"""Project installation and environment requirements.

1. Offline tracking with cached keypoint CSV files
   In a separate Python environment, run from this directory:
       python -m pip install -e .
   install_requires installs NumPy, SciPy, OpenCV, PyYAML, and scikit-image.
   The default ELSED backend also builds a native extension: install a C++14
   compiler, pkg-config, OpenCV development libraries, and matching Python
   headers. PEP 517 installs pybind11 for builds; colcon/build_ext requires
   pybind11 headers already available. Prefer headers/libraries from the
   same OpenCV installation; Conda pkg-config is selected when available.
   Offline regression environment: Python 3.8.20, NumPy 1.24.3,
   SciPy 1.10.1, OpenCV 4.10.0, and PyYAML 6.0.3.
   These are tested versions; other version combinations are not all verified.
   Canny/Hough and optional shaft skeletonization dependencies are included.
   For test tools: python -m pip install -e '.[test]'

2. Online keypoint inference (configured separately, not installed here)
   dekr_live_runner requires torch and the DLCLive PyTorch backend, including:
       dlclive.pose_estimation_pytorch.models.predictors.identity_predictor
   dlc_runner requires the DeepLabCut PyTorch inference API.
   Local DLC environment: Python 3.10.20, torch 2.6.0+cu124,
   torchvision 0.21.0+cu124, and deeplabcut 3.0.0.
   dlclive was not found in that environment; it is not a verified complete
   online environment. Select compatible DLCLive/DeepLabCut, PyTorch, and
   torchvision versions based on the model export environment.
   GPU inference also requires an NVIDIA driver compatible with the PyTorch
   CUDA build. Supply DEKR .pt weights separately through model path settings.

3. ROS 2 online/offline nodes (system dependencies, not installed by pip)
   The project currently uses Linux and ROS 2 Humble. Use a Python interpreter
   compatible with the ROS binaries.
   Required packages include ament_python, ament_index_python, rclpy,
   message_filters, tf2_ros, sensor_msgs, geometry_msgs, cv_bridge,
   visualization_msgs, launch, launch_ros, and the colcon build tools.
   Source /opt/ros/humble/setup.bash before running these workspace commands:
       rosdep install --from-paths src --ignore-src -r -y
       colcon build --packages-select surgical_tool_tracking_ros2
       source install/setup.bash
   The direct GStreamer camera backend additionally requires system
   PyGObject (gi), GStreamer 1.0, GstApp introspection, and the plugins used
   by the capture pipeline. OpenCV capture/display also requires suitable
   system video backends and a graphical environment.

4. Required resources (not generated by dependency installation)
   Parameter/stereo_calibration.yaml: stereo calibration matching the cameras.
   Parameter/LND.json: tool geometry and kinematic parameters.
   Valid hand-eye calibration YAML: specify --handeye for offline use;
   a missing calibration file raises an error.
   Offline data: stereo images, joint data, and keypoint CSV files.
   Online data: camera input, robot joint messages, and detection weights.
"""
from setuptools import Extension, find_packages, setup
from setuptools.command.build_ext import build_ext
import shlex
import sys
import subprocess
import os
from glob import glob

class ElsedBuildExt(build_ext):
    def build_extensions(self):
        env = os.environ.copy()
        prefix_pc = os.path.join(sys.prefix, "lib", "pkgconfig")
        env["PKG_CONFIG_PATH"] = os.pathsep.join(
            filter(None, [prefix_pc, env.get("PKG_CONFIG_PATH", "")]))
        try:
            flags = shlex.split(subprocess.check_output(
                ["pkg-config", "--cflags", "--libs", "opencv4"], text=True, env=env))
        except (OSError, subprocess.CalledProcessError) as exc:
            raise RuntimeError("ELSED build requires pkg-config and OpenCV development libraries.") from exc
        try:
            import pybind11
            pybind_include = pybind11.get_include()
        except ImportError:
            pybind_include = "/usr/include"
            if not os.path.isfile(os.path.join(pybind_include, "pybind11/pybind11.h")):
                raise RuntimeError("ELSED build requires pybind11 headers.")
        for extension in self.extensions:
            extension.include_dirs.append(pybind_include)
            for flag in flags:
                if flag.startswith("-I"):
                    extension.include_dirs.append(flag[2:])
                elif flag.startswith("-L"):
                    extension.library_dirs.append(flag[2:])
                elif flag in ("-lopencv_core", "-lopencv_imgproc"):
                    extension.libraries.append(flag[2:])
                elif flag.startswith("-l"):
                    continue
                else:
                    extension.extra_link_args.append(flag)
        super().build_extensions()


elsed_source = "tracking/features/elsed_src"
package_name = 'surgical_tool_tracking_ros2'

setup(
    name=package_name,
    version='0.1.0',
    ext_modules=[Extension(
        "tracking.features._elsed_native",
        sources=[os.path.join(elsed_source, name) for name in
                 ("bindings.cpp", "ELSED.cpp", "EdgeDrawer.cpp", "FullSegmentInfo.cpp")],
        include_dirs=[elsed_source], language="c++",
        extra_compile_args=["-O3", "-std=c++14"], extra_link_args=[],
    )],
    cmdclass={"build_ext": ElsedBuildExt},
    package_data={"tracking.features": ["elsed_src/*.h", "elsed_src/*.cpp", "elsed_src/LICENSE"]},
    packages=find_packages(include=['tracking', 'tracking.*', 'FPRT', 'APRT']),
    data_files=[
        ('share/ament_index/resource_index/packages',
            ['resource/' + package_name]),
        ('share/' + package_name, ['package.xml']),
        (os.path.join('share', package_name, 'launch'),
            glob('launch/*.launch.py')),
        (os.path.join('share', package_name, 'Parameter'),
            glob('Parameter/*')),
        # Hand-eye calibration YAMLs, if any are checked in at the package
        # root (see tracking/messages/arm_configs.py's build_arm_configs() fallback
        # search) -- glob() is fine with zero matches, unlike a literal
        # missing filename in data_files.
        (os.path.join('share', package_name),
            glob('pnp_*.yaml')),
    ],
    python_requires='>=3.8',
    install_requires=['setuptools', 'numpy', 'scipy', 'opencv-python', 'PyYAML', 'scikit-image'],
    extras_require={
        'skeleton': [],  # Retained for compatibility; included by default.
        'test': ['pytest'],
    },
    zip_safe=True,
    maintainer='Yao Chen',
    maintainer_email='ychen777@jh.edu',
    description='Dual-arm surgical tool tracking ROS2 node',
    license='MIT',
    entry_points={
        'console_scripts': [
            'fprt_offline = FPRT.offline_tracking:main',
            'aprt_offline = APRT.offline_tracking:main',
            'fprt_tracking_node = FPRT.ros_tracking:main',
            'aprt_tracking_node = APRT.ros_tracking:main',
            'fprt_offline_node = FPRT.ros_offline:main',
            'aprt_offline_node = APRT.ros_offline:main',
            'tracking_node = tracking.messages.tracking_node:main',
            'offline_node = tracking.messages.offline_node:main',
            'dvrk_stereo_publisher = tracking.messages.dvrk_stereo_publisher:main',
        ],
    },
)
